# 3.2.0-beta.7: per F(X) table (S<stn>-LN<n>): the axis names of the workbook chart and the signal path read from the app
# (tools/fx/trace.js): the sheets that use it, what feeds the input, where the output goes. Writes src/ui/fx/fx-paths.js.
# Usage: python3 tools/fx/paths.py trace.json > src/ui/fx/fx-paths.js
import json, re, sys
tr = json.load(open(sys.argv[1]))
ax = json.load(open(__file__.rsplit('/', 1)[0] + '/axis.json'))
GEN = re.compile(r'^(?:[A-Z0-9]+ out|→.*|F\(X\)|COS .*|f\(t\)|\[.*\]|\d+[A-Z]?|STN\d+|USED)$')
def tag(n):
    m = re.match(r'^(?:PID|PIDV|MAN) (\S+) out$', n)
    return m.group(1) if m else n
def keep(n, d):
    if GEN.match(n): return False
    if re.match(r'^(S\d )?SI\d+$', n) and (not d or d.startswith('USED')): return False
    return True
P = {}
for r in tr:
    m = re.search(r'LN(\d+)', r['ln'] or '')
    if not m or r['stn'] is None: continue
    k = 'S%d-LN%d' % (r['stn'], int(m.group(1)))
    q = P.setdefault(k, {'sh': [], 'in': [], 'up': [], 'dn': []})
    if r['sheet'] not in q['sh']: q['sh'].append(r['sheet'])
    for n in map(tag, r['in']):
        if n and n not in q['in'] and not GEN.match(n): q['in'].append(n)
    for u in (r['up'][:1] if r['up'] else []):
        for x in u:
            if x.get('d2'): continue
            n, d = tag(x['n']), x.get('d', '')
            if keep(n, d) and [n, d] not in q['up']: q['up'].append([n, d])
    for dd in (r['dn'][:1] if r['dn'] else []):
        for x in dd:
            for o in x['outs']:
                n, d = tag(o['n']), o.get('d', '')
                if keep(n, d) and [n, d] not in q['dn']: q['dn'].append([n, d])
for k, q in P.items():
    q['up'] = q['up'][:10]; q['dn'] = q['dn'][:14]
A = {}
for k, L in ax.items():
    y = next((t for t, v in L if v), ''); x = next((t for t, v in L if not v), '')
    A[k] = [x, y]
sys.stdout.write('/* generated by tools/fx/paths.py (3.2.0-beta.7): axis names of the LINEAR CURVE workbook charts and the signal path of each F(X) table read from the drawings in this app */\nwindow.LS_FXPATH=' + json.dumps({'axis': A, 'path': P}, ensure_ascii=False, separators=(',', ':')) + ';\n')
