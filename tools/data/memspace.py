# Vacant addresses of the memory lists (document-references/memory-list-10N.xls): the rows with no description, per station and
# sheet, as runs [first address, count] -> src/ui/plant/memspace.js (LIBRARY > MEMORY LIST shows them like the I/O list).
# The Excel writes the full address every 10 / 16 rows and only the last digit between (M.0000, 1, 2 ... F, M.0010).
# Usage: python3 tools/data/memspace.py
import xlrd, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
def s(v):
    if isinstance(v, float):
        return str(int(v)) if v == int(v) else str(v)
    return str(v).strip()
def nxt(a, hx):
    m = re.match(r'^([A-Z]+\.?)([0-9A-F]+)$', a)
    p, n = m.group(1), m.group(2)
    v = int(n, 16 if hx else 10) + 1
    return p + (format(v, 'X') if hx else str(v)).zfill(len(n))
out = {}
tot = 0
for st in '12345':
    b = xlrd.open_workbook(os.path.join(ROOT, 'document-references', 'memory-list-10' + st + '.xls'))
    for sh in b.sheets():
        kind = re.search(r'\((\w+)\)', sh.name).group(1)
        hdr = [s(c.value).lower() for c in sh.row(0)]
        di = next(i for i, h in enumerate(hdr) if h.startswith('description'))
        base, runs, prev = None, [], None
        col = [s(sh.cell_value(r, 1)) for r in range(1, sh.nrows)]
        hx = any(re.match(r'^[A-F]$', a) or re.match(r'^[A-Z]+\.?[0-9]*[A-F][0-9A-F]*$', a[2:] if a[:2] in ('M.', 'B.') else a[len(re.match(r'^[A-Z]+', a).group(0)) if re.match(r'^[A-Z]+', a) else 0:]) for a in col if a)
        for r in range(1, sh.nrows):
            a = s(sh.cell_value(r, 1))
            if re.match(r'^[A-Z]+\.?[0-9A-F]{3,}$', a):
                base = a
            elif base and re.match(r'^[0-9A-F]$', a):
                a = base[:-1] + a
            else:
                continue
            d = s(sh.cell_value(r, di)) if di < sh.ncols else ''
            if d:
                prev = None
                continue
            if prev is not None and nxt(prev, hx) == a:
                runs[-1][1] += 1
            else:
                runs.append([a, 1])
            prev = a
            tot += 1
        out.setdefault(st, {})[kind] = {'h': 1 if hx else 0, 'r': runs}
dst = os.path.join(ROOT, 'src', 'ui', 'plant', 'memspace.js')
with open(dst, 'w') as f:
    f.write('/* Vacant addresses of the memory lists, generated by tools/data/memspace.py: station -> sheet -> {h: hexadecimal numbering, r: [[first address, count]]} (no description in the Excel). */\n')
    f.write('window.MEM_VACANT = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(tot, 'vacant addresses ->', dst, os.path.getsize(dst), 'bytes')
print({st: {k: (v['h'], sum(c for _, c in v['r']), len(v['r'])) for k, v in out[st].items()} for st in out})
