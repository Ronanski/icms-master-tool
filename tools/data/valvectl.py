# Valve -> controller of the control-room HMI snapshots (docs/hmi/operating-points.json: a "valve" item and its abcTag)
# -> src/ui/plant/valvectl.js. The PLANT workspace shows the MV of that controller as the valve opening (the HMI shows the MV;
# the signal at the valve on the drawing can be inverted, 100 - MV, for a fail-open valve). Usage: python3 tools/data/valvectl.py
import json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
d = json.load(open(os.path.join(ROOT, 'docs', 'hmi', 'operating-points.json')))
N = lambda t: re.sub(r'[^A-Z0-9]', '', str(t).upper())
out = {}
for im in d:
    for it in im['items']:
        t, c = it.get('tag'), it.get('abcTag')
        if it.get('kind') == 'valve' and t and c and '~' not in c and re.match(r'^[A-Z0-9-]+$', c):
            out.setdefault(N(t), c)
dst = os.path.join(ROOT, 'src', 'ui', 'plant', 'valvectl.js')
with open(dst, 'w') as f:
    f.write('/* Valve tag -> its controller on the HMI snapshots, generated by tools/data/valvectl.py from docs/hmi/operating-points.json. */\n')
    f.write('window.PLANT_VALVE_CTL = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(out), 'valves ->', dst)
