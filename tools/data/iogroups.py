# I/O list grouping (document-references/dcs-io-list.xls): per station sheet, the node (N), I/O unit (I) and channel (NO) of every
# address, and the HMI picture (PICT) -> src/ui/plant/iogroups.js (LIBRARY > I/O LIST groups). Usage: python3 tools/data/iogroups.py
import xlrd, json, os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
b = xlrd.open_workbook(os.path.join(ROOT, 'document-references', 'dcs-io-list.xls'))
num = lambda x: int(x) if isinstance(x, float) else (int(x) if str(x).strip().isdigit() else str(x).strip())
out = {}
for sh in b.sheets():
    m = re.match(r'Station 10(\d)', sh.name)
    if not m:
        continue
    st = m.group(1)
    hdr = [str(c.value).strip() for c in sh.row(2)]
    for r in range(3, sh.nrows):
        row = sh.row(r)
        a = str(row[4].value).strip() if len(row) > 4 else ''
        if not re.match(r'^(I\.|O\.|AI|AO|PI|PO)[0-9A-F]{3,4}$', a):
            continue
        pict = ''
        for c in row[14:]:
            if re.match(r'^PICT\s*\d+', str(c.value).strip()):
                pict = str(c.value).strip()
        out[st + '|' + a] = [num(row[1].value), num(row[2].value), num(row[3].value), pict]
dst = os.path.join(ROOT, 'src', 'ui', 'plant', 'iogroups.js')
with open(dst, 'w') as f:
    f.write('/* I/O list grouping, generated by tools/data/iogroups.py from document-references/dcs-io-list.xls: "station|address": [node N, I/O unit I, channel NO, HMI picture]. */\n')
    f.write('window.IO_GROUPS = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(out), 'addresses ->', dst)
