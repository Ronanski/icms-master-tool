# 3.2.0 R9 #81 #82 #74: the Tag no., Operating Limits (Normal / Alarm / Trip) and Responsible (SS/SV, CRO, AO, WTP, MH) columns of the
# table row of every numbered step of PR-OPE-5002, and the steps that are part of a NOTE (not something to tick). Same walk over the
# paragraphs as extract.py, so the keys "section.step" (0-based) are the ones of src/ui/training/pr-ope-5002.js.
# Usage: python3 tools/training/extract_limits.py > src/ui/training/pr-ope-5002-lim.js
import re, sys, zipfile, json, html, bisect
src = sys.argv[1] if len(sys.argv) > 1 else 'document-references/procedure-start-up-PR-OPE-5002-02.docx'
x = zipfile.ZipFile(src).read('word/document.xml').decode('utf8')
txt = lambda s: re.sub(r'\s+', ' ', html.unescape(''.join(re.findall(r'<w:t[^>]*>([^<]*)</w:t>', s)))).strip()
# the table rows and their cells (grid column of each cell)
rows = []
for m in re.finditer(r'<w:tr[ >].*?</w:tr>', x, flags=re.S):
    cells, col = [], 0
    for c in re.finditer(r'<w:tc[ >].*?</w:tc>', m.group(0), flags=re.S):
        sp = re.search(r'<w:gridSpan w:val="(\d+)"', c.group(0))
        sp = int(sp.group(1)) if sp else 1
        cells.append((col, ' '.join(txt(p) for p in re.findall(r'<w:p[ >].*?</w:p>', c.group(0), flags=re.S)).strip()))
        col += sp
    rows.append((m.start(), m.end(), cells))
starts = [r[0] for r in rows]
def row_of(pos):
    i = bisect.bisect_right(starts, pos) - 1
    return rows[i] if i >= 0 and rows[i][0] <= pos < rows[i][1] else None
NOT = {'PR-OPE-5002'}
secs, cur, started, last, hdr = [], None, False, None, {}
out = {}
note_row = None
for pm in re.finditer(r'<w:p[ >].*?</w:p>', x, flags=re.S):
    p = pm.group(0)
    sty = re.search(r'<w:pStyle w:val="([^"]+)"', p)
    sty = sty.group(1) if sty else ''
    num = '<w:numPr>' in p
    t = txt(p)
    r = row_of(pm.start())
    # the header row of a table: the grid column of each limit / responsible name
    if r and any(c[1] == 'Normal' for c in r[2]):
        hdr = {c[0]: c[1] for c in r[2] if c[1]}
    if not t: continue
    if t.upper() == 'PROCEDURES': started = True; continue
    if not started: continue
    if sty.startswith('Heading2'):
        if num:
            cur = {'s': []}; secs.append(cur); last = None
        continue
    if cur is None: continue
    if r and re.match(r'^\s*note\b', t, re.I): note_row = r[0]
    if sty.startswith('ListParagr') and num:
        if t in ('Equipment/Procedure',): continue
        last = {'t': t}; cur['s'].append(last)
        if r:
            c = {col: v for col, v in r[2]}
            cols = sorted(c)
            inv = {v: k for k, v in hdr.items()}
            def at(name, k):
                return c.get(inv.get(name, k), '')
            lim = {'g': c.get(1, '') if 1 in c else '', 'n': at('Normal', 2), 'a': at('Alarm', 3), 'tr': at('Trip', 4)}
            # the first cell is the step itself; a tag cell that holds the step text again is not a tag
            if lim['g'] == t or len(lim['g']) > 60: lim['g'] = ''
            by = [n for k, n in hdr.items() if n in ('SS/SV', 'CRO', 'AO', 'WTP', 'MH') and c.get(k, '') in ('√', '/')]
            if by: lim['by'] = '/'.join(by)
            # a step written after "NOTE" in the same cell (the auto-start conditions of section 16, the bearing oil temperatures of 14)
            c0 = c.get(0, '')
            nm = re.search(r'\bNOTE\b\s*:?', c0, re.I)
            if note_row == r[0] or (nm and t[:25] in c0 and c0.index(t[:25]) > nm.start()):
                # a line of the NOTE: no limit, no tick; the whole NOTE is shown once (x)
                lim = {'note': 1, 'x': c0[nm.start():] if nm else c0}
            elif nm and t[:25] in c0 and c0.index(t[:25]) < nm.start():
                lim['x'] = c0[nm.start():]  # the NOTE written under the step (lube oil cooler: 37 / 46 C)
            last['lim'] = {k: v for k, v in lim.items() if v}
secs = [s for s in secs if s['s']]
for si, s in enumerate(secs):
    for i, st in enumerate(s['s']):
        if st.get('lim'): out['%d.%d' % (si, i)] = st['lim']
sys.stdout.write('/* generated by tools/training/extract_limits.py (3.2.0 R9 #81) from document-references/procedure-start-up-PR-OPE-5002-02.docx: per step '
  '"section.step" (0-based, as LS_PROC5002) the Tag no. (g), the Operating Limits Normal (n) / Alarm (a) / Trip (tr), the Responsible (by) and '
  'note = 1 for a line of a NOTE (read, not ticked) */\nwindow.LS_PROC5002_LIM=' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';\n')
