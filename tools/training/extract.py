# 3.2.0-beta.8: the step list of the start-up procedure PR-OPE-5002 (document-references/procedure-start-up-PR-OPE-5002-02.docx)
# for the Training page. Sections = the numbered Heading 2 titles after PROCEDURES; steps = the numbered paragraphs under them;
# tags = the tag numbers in the step text or in the Tag no. cells that follow the step.
# Usage: python3 tools/training/extract.py > src/ui/training/pr-ope-5002.js
import re, sys, zipfile, json, html
src = sys.argv[1] if len(sys.argv) > 1 else 'document-references/procedure-start-up-PR-OPE-5002-02.docx'
x = zipfile.ZipFile(src).read('word/document.xml').decode('utf8')
TAG = re.compile(r'\b(?:[A-Z]{1,4}-?[A-Z]{1,3}-?\d{3,5}(?:-?[A-Z0-9]{1,2})?|[A-Z]-\d{3,4}|F\d{4})\b')
NOT = {'PR-OPE-5002'}
secs, cur, started, last = [], None, False, None
for p in re.findall(r'<w:p[ >].*?</w:p>', x, flags=re.S):
    sty = re.search(r'<w:pStyle w:val="([^"]+)"', p)
    sty = sty.group(1) if sty else ''
    num = '<w:numPr>' in p
    t = html.unescape(''.join(re.findall(r'<w:t[^>]*>([^<]*)</w:t>', p))).strip()
    t = re.sub(r'\s+', ' ', t)
    if not t: continue
    if t.upper() == 'PROCEDURES': started = True; continue
    if not started: continue
    if sty.startswith('Heading2'):
        if num:
            cur = {'t': t, 'note': '', 's': []}; secs.append(cur); last = None
        elif cur and t.lower().startswith('note'):
            cur['note'] = t
        continue
    if cur is None: continue
    if sty.startswith('ListParagr') and num:
        if t in ('Equipment/Procedure',): continue
        last = {'t': t, 'g': []}; cur['s'].append(last)
        for m in TAG.findall(t):
            if m not in NOT and m not in last['g']: last['g'].append(m)
    elif last is not None and not sty.startswith('ListParagr'):
        if t in ('√', '/') or len(t) > 160: continue
        for m in TAG.findall(t.replace(' ', '')) + TAG.findall(t):
            if m not in NOT and m not in last['g']: last['g'].append(m)
secs = [s for s in secs if s['s']]
sys.stdout.write('/* generated by tools/training/extract.py (3.2.0-beta.8) from document-references/procedure-start-up-PR-OPE-5002-02.docx: '
  'the sections and numbered steps of the START-UP PROCEDURE PR-OPE-5002 (Rev 03, 2025-01-13), with the tag numbers of each step */\n'
  'window.LS_PROC5002=' + json.dumps(secs, ensure_ascii=False, separators=(',', ':')) + ';\n')
