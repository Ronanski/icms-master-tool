#!/usr/bin/env python3
"""Makes hx-registry.js: every machine, valve and control loop that the 19 temporary pages of the app already bind (name, English
text, the binding of the app: DITL sheet / address / controller tag) and ONE set of sample values = what the app itself shows at
"Start at 150 MW" (3.2.3-beta.272). Nothing is typed by hand here.
Inputs: summary.json (mach{} of every src/ui/plant/hmi-mock-*.js) and live150.json (tools/dump-live150.js run on the built app).
Usage: python3 make-registry.py summary.json live150.json > ../hx-registry.js"""
import json, re, sys
summ = json.load(open(sys.argv[1])); live = json.load(open(sys.argv[2]))
num = lambda s: (lambda m: float(m.group(0)) if m else None)(re.search(r'-?\d+(?:\.\d+)?', (s or '').replace('−', '-'))) if '-----' not in (s or '-----') else None
mach, loops, vals, states, valves, modes = {}, {}, {}, {}, {}, {}
for p in summ:
    pid = p['id']; lv = live.get(pid, {})
    st = {x['id']: x['t'] for x in lv.get('st', [])}; md = {x['id']: x['t'] for x in lv.get('md', [])}
    for k, m in (p.get('mach') or {}).items():
        name = m.get('n'); b = {x: m[x] for x in m if x not in ('n', 't')}
        if m.get('ctl') or (name in (p.get('ctlTags') or [])):
            loops.setdefault(m.get('ctl') or name, {'t': m.get('t'), 'page': pid, 'id': k})
            continue
        e = mach.setdefault(name, {'t': m.get('t'), 'page': pid, 'id': k, 'bind': b})
        if k in st: states[name] = 'run' if st[k].upper().startswith('RUN') else 'trip' if 'TRIP' in st[k].upper() else 'stop'
        if k in md: modes[name] = md[k]
    for t in (p.get('ctlTags') or []): loops.setdefault(t, {'t': '', 'page': pid})
    for x in lv.get('v', []):
        v = num(x['t'])
        if v is not None and x['tag'] not in vals: vals[x['tag']] = v
        elif x['tag'] not in vals: vals[x['tag']] = None
    for x in lv.get('ctl', []):
        a = x['c'].split('|'); L = loops.setdefault(a[0], {'t': '', 'page': pid}); s = L.setdefault('s', {})
        if a[1] == 'mode': s['mode'] = x['t'].strip().upper() if '-----' not in x['t'] else s.get('mode')
        else:
            v = num(x['t'])
            if v is not None: s[a[1]] = v
            u = re.sub(r'^[-\d.\s]+', '', x['t']).strip()
            if a[1] in ('pv', 'sv') and u and '-----' not in u: s['unit'] = u
    for x in lv.get('mov', []):
        a = (x.get('m') or '').split('|')
        if len(a) < 3 or a[1].startswith('~'): continue
        V = valves.setdefault(a[1], {'bind': a[0]})
        if a[2] == 'pct': V['pct'] = num(x['t'])
        elif a[2] == 'oc': V['open'] = x['t'] == 'OPEN'
        else: V['mode'] = x['t']
strip = live.get('_strip', [])
out = {'from': 'app 3.2.3-beta.272, Start at 150 MW, 20 s after Run', 'machines': mach, 'loops': loops, 'sample': {'values': vals, 'states': states, 'modes': modes, 'valves': valves}}
print('/* GENERATED by tools/make-registry.py from the app itself (see README). Do not edit by hand. */')
print('window.HXREG = ' + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ';')
