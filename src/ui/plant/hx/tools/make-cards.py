#!/usr/bin/env python3
"""Makes hx-cards.js: what the two mini pop-ups of the HX pages show for each valve and loop of the reheat sample.
Nothing is typed by hand: the rows are what the app itself reads from its logic (3.2.3-beta.272, Start at 150 MW):
  cards-rows.json        every row of the DITL sheet of a valve: service text, address, live value (DUI.rowInfo / rowVal)
  cards-perm.json        the permissive rows of a motor valve as the app computes them (LS_DOCK.interlock: row, wanted state)
  cards-faceplates.json  the text of the app's own faceplate of each controller: name, range, which mode buttons exist
Usage: python3 make-cards.py cards-rows.json cards-perm.json cards-faceplates.json > ../hx-cards.js"""
import json, re, sys
rows, perm, fps = (json.load(open(a)) for a in sys.argv[1:4])
valves = {}
for tag, v in rows.items():
    if tag.startswith('_'): continue
    R = v.get('rows') or []
    svc = lambda r: re.sub(r'\s+', ' ', r.get('svc') or '').strip()
    has = lambda pat: any(re.search(pat, svc(r)) for r in R)
    pr = {p['row']: p for p in (perm.get('mov', {}).get(tag, {}).get('rows') or [])}
    perms, reads, mon = [], [], []
    for r in R:
        s = svc(r); ref = v['ad'].split(' ')[0] + ' row ' + str(r['r'] + 1) + (' · ' + r['tag'] if r.get('tag') else '')
        if r['r'] in pr:
            perms.append({'t': s, 'need': pr[r['r']]['want'], 'is': 1 if r.get('v') else 0, 'ref': ref}); continue
        if re.search(r'\bP\.?B\.?$|\bPB\b|P\.B\.', s): continue                       # the push buttons of the screen
        if re.search(r'(AUTO|MANUAL)( MODE)? SELECTED|AUTO MODE$', s): continue       # shown as the mode
        if re.search(r'FULL(Y)? ?(OPEN|CLOSE)|SOV CLOSED|TORQUE|MOV POSITION|(OPEN|CLOSED?) COMMAND$|\bREMOTE( MODE SELECTED)?$', s) and not re.search(r'NO\.[23] ', s.replace('NO.1', '')):
            mon.append({'t': s, 'is': 1 if r.get('v') else 0, 'ref': ref}); continue
        reads.append({'t': s, 'is': 1 if r.get('v') else 0, 'ref': ref})
    valves[tag] = {'sheet': v['ad'], 'title': re.sub(r'\s+', ' ', v.get('title') or ''), 'am': has(r'AUTO'), 'field': has(r'\bREMOTE\b'), 'stop': has(r'STOP P\.?B'),
                   'perms': perms, 'reads': reads, 'mon': mon}
loops = {}
for k, v in fps.items():
    for p in v.get('pops', []):
        if 'fpx' not in p['cls']: continue
        t = [x.strip() for x in p['text'].split('\n') if x.strip()]
        tag = next((x for x in t if re.fullmatch(r'[A-Z]{2,4}-?[A-Z]*\d{3,5}[A-Z]?', x)), None)
        rng = next((x for x in t if x.startswith('[')), '')
        m = re.match(r'\[([-\d.]+) ~ ([-\d.]+) ?([^\]]*)\]', rng)
        note = next((x for x in t if re.search(r'SV|REMOTE:|LOCAL:', x) and len(x) > 6 and 'Engineering' not in x), '')
        modes = [b for b in p['btn'] if b in ('R', 'A', 'M', 'MAN')]
        pv = None
        if 'PV' in t:
            i = t.index('PV')
            try: pv = float(t[i + 2])
            except Exception: pv = None
        loops[tag] = {'name': t[0], 'lo': float(m.group(1)) if m else None, 'hi': float(m.group(2)) if m else None, 'unit': m.group(3) if m else '', 'modes': modes, 'note': note, 'pv': pv}
print('/* GENERATED by tools/make-cards.py from the logic of the app itself (see README 6c). Do not edit by hand. */')
print('window.HXCARDS = ' + json.dumps({'from': 'app 3.2.3-beta.272, Start at 150 MW', 'valves': valves, 'loops': loops}, ensure_ascii=False, separators=(',', ':')) + ';')
